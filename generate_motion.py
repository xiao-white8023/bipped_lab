def generate_motion():
    num_keyframes = len(keyframes)
    num_joints = 29
    
    # 1. 准备时间轴
    # 假设关键帧在时间轴上是均匀分布的
    keyframe_times = np.linspace(0, TOTAL_DURATION, num_keyframes)
    
    # 生成目标时间点 (例如 50Hz 下，3.5秒会生成 175 个点)
    target_num_frames = int(TOTAL_DURATION * FPS)
    target_times = np.linspace(0, TOTAL_DURATION, target_num_frames)
    
    final_frames = []
    
    # 2. 转换数据格式以便计算
    # 构建一个矩阵 (num_keyframes, num_joints)
    joint_data_matrix = np.zeros((num_keyframes, num_joints))
    
    for i, frame in enumerate(keyframes):
        for joint_id in range(num_joints):
            joint_data_matrix[i, joint_id] = frame.get(str(joint_id), 0.0)

    # 3. 对每个关节进行 PCHIP 插值
    interpolated_data = np.zeros((target_num_frames, num_joints))
    
    for joint_id in range(num_joints):
        y_values = joint_data_matrix[:, joint_id]
        
        # 创建插值器
        interpolator = PchipInterpolator(keyframe_times, y_values)
        
        # 计算新帧的值
        interpolated_values = interpolator(target_times)
        interpolated_data[:, joint_id] = interpolated_values

    # 4. 封装回 JSON 格式
    output_frames = []
    for t in range(target_num_frames):
        frame_dict = {}
        for joint_id in range(num_joints):
            # 将 numpy float 转为 python float，保留一定精度
            frame_dict[str(joint_id)] = float(interpolated_data[t, joint_id])
        output_frames.append(frame_dict)
    
    result = {"frames": output_frames}
    
    # 5. 保存文件
    with open(OUTPUT_FILENAME, 'w') as f:
        json.dump(result, f, indent=None) # indent=None 减小文件体积
        
    print(f"成功生成动作文件: {OUTPUT_FILENAME}")
    print(f"总时长: {TOTAL_DURATION}s, 总帧数: {len(output_frames)}")

if __name__ == "__main__":
    generate_motion()
